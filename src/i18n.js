let current = null;

/** The stored language, or null if the player hasn't chosen yet. */
export function storedLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return LANGUAGES.some((l) => l.id === saved) ? saved : null;
  } catch {
    return null;
  }
}

/**
 * A guess for the strings shown BEFORE the choice is made - the account gate
 * and the language dialog itself. It is never stored, so the choice is still
 * the player's; it only stops a French phone being greeted in English.
 */
function guessLanguage() {
  const wanted = (navigator.languages ?? [navigator.language ?? '']).map((tag) =>
    String(tag).slice(0, 2).toLowerCase());
  return wanted.find((code) => LANGUAGES.some((l) => l.id === code)) ?? 'en';
}


/**
 * Bring in the chosen language's table before anything is drawn. English is
 * already here; French arrives as its own chunk. Called once from main.js,
 * ahead of the first paint, so no screen is ever written in the wrong
 * language and then corrected.
 */

export async function loadLanguage() {
  const id = getLanguage();
  if (id === 'en' || STRINGS[id]) return;
  try {
    const pack = await import('./i18n-fr.js');
    STRINGS.fr = pack.fr;
  } catch {
    /* The English fallback below carries the app until the next load. */
  }
}

export function getLanguage() {
  if (!current) current = storedLanguage() ?? guessLanguage();
  return current;
}

/** Locked after the first choice - see the note at the top of this file. */
export function setLanguage(id) {
  if (!LANGUAGES.some((l) => l.id === id)) return getLanguage();
  current = id;
  try { localStorage.setItem(LANG_KEY, id); touch(LANG_KEY); } catch { /* session-only */ }
  touch();
  return current;
}

export const languageChosen = () => storedLanguage() !== null;

/** The Wikipedia subdomain for the current language. */
export const wikiLang = () =>
  LANGUAGES.find((l) => l.id === getLanguage())?.wiki ?? 'en';

/** Look up a UI string, filling {placeholders}. */
export function t(key, vars = {}) {
  const table = STRINGS[getLanguage()] ?? STRINGS.en;
  const raw = table[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`);
}

/**
 * Resolve a `{ en, fr }` value from a data table. Data files keep their own
 * translations next to the thing they describe rather than through a key.
 */
export function tx(value) {
  if (typeof value === 'string') return value;
  if (!value) return '';
  return value[getLanguage()] ?? value.en ?? '';
}
